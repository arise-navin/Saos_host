/**
 * HEALTH ASSIST PHASE 3 — run the scoring calibration and write the report.
 *
 *   node scripts/health-calibrate.mjs
 *
 * Writes:
 *   src/health/scoring/calibration-report.json   the full, deterministic result (the suite checks it is current)
 *   ../docs/HEALTH-ASSIST-CALIBRATION.md          the same, for review
 *
 * Promotes nothing (decision D-008): the report is the input to a decision.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { runCalibration } from '../src/health/scoring/calibration.js';
import { ALL_SCENARIOS } from '../src/health/scoring/scenarios.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SCORING = path.resolve(HERE, '../src/health/scoring');
const candidates = JSON.parse(fs.readFileSync(path.join(SCORING, 'candidates.json'), 'utf8'));
const report = runCalibration(candidates);

fs.writeFileSync(path.join(SCORING, 'calibration-report.json'), `${JSON.stringify(report, null, 1)}\n`);

/* ── the reviewable document ── */
const yes = (b) => (b ? 'pass' : '**FAIL**');
const PROPS = {
  P1: 'Monotonicity', P2: 'Severity ordering', P3: 'No masking', P4: 'Dilution resistance',
  P5: 'Authoring invariance', P6: 'Coverage honesty', P7: 'Applicability neutrality', P8: 'Stability',
};
const lines = [];
const out = (s = '') => lines.push(s);

out('# Health Assist — Scoring Calibration Report');
out();
out(`**Calibration** \`${report.calibration_version}\` · **candidates** \`${report.candidates_version}\` · **promoted: ${report.promoted}**`);
out();
out(`Generated by \`server/scripts/health-calibrate.mjs\` from \`server/src/health/scoring/\`. The harness is deterministic: re-running it reproduces this document exactly, and \`test/health-scoring.test.js\` fails if the committed report is stale.`);
out();
out(`> ${report.promotion_rule}`);
out();
out('## Verdict');
out();
out(report.combined.passes_all
  ? 'The combined configuration below passes every property and every scenario. It can be put forward for a promotion decision.'
  : `The combined configuration below **does not pass everything**: ${report.combined.failing.length} check(s) fail under it. Each one needs a decision: change the method, or change the expectation (with the reason recorded). **Nothing is promoted.**`);
out();
out('| Axis | Leader | Options passing everything the axis decides |');
out('|---|---|---|');
for (const [axis, a] of Object.entries(report.axes)) {
  const o = a.options.find((x) => x.id === a.leader);
  out(`| ${axis.replace(/_/g, ' ')} | **${a.leader}**: ${o.describe} | ${a.options_passing_axis.length ? a.options_passing_axis.join(', ') : 'none'} |`);
}
out();
if (report.combined.failing.length) {
  out('**Still failing under the combined leaders:**');
  out();
  for (const f of report.combined.failing) out(`- ${f}`);
  out();
}
out('**How the leaders were found.** Each axis is judged with every other axis held at its current leader, and the passes repeat until no leader changes. Ties go to the option that adds no mechanism, then the one already held (candidates.json `tie_break`).');
out();
out('| Pass | ' + Object.keys(report.axes).map((a) => a.replace(/_/g, ' ')).join(' | ') + ' |');
out('|---|' + Object.keys(report.axes).map(() => '---').join('|') + '|');
for (const p of report.convergence) out(`| ${p.pass} | ${Object.keys(report.axes).map((a) => p.leaders[a]).join(' | ')} |`);
out();
out('See also [HEALTH-ASSIST-CALIBRATION-INVESTIGATION.md](HEALTH-ASSIST-CALIBRATION-INVESTIGATION.md): what the first report failed, the exact arithmetic, and the fixes tested.');
out();
out('## Acceptance rules');
out();
out(`- *Materially unhealthy* means below **${report.acceptance.unhealthy_below}**. That is the product's existing "Needs work" band, and it is an assumption for you to review.`);
out(`- Dilution tolerance: ${report.acceptance.dilution_tolerance_points} points. Stability tolerance: ${report.acceptance.stability_tolerance_points} points for a ±${report.acceptance.stability_perturbation * 100}% change in any number. Masking slack: ${report.acceptance.masking_band_slack} band.`);
out('- P1 Monotonicity: fixing a defect never lowers a score, and adding one never raises it.');
out('- P2 Severity ordering: Systemic costs more than Critical, which costs more than High, then Moderate, then Low.');
out('- P3 No masking: one materially unhealthy module shows in the Overall band **and** number.');
out('- P4 Dilution resistance: a clean tail growing from 10 to 10,000 records moves a defective core\'s dimension by at most the tolerance.');
out('- P5 Authoring invariance: one condition restated as two rules (same family, or same charge key) scores the same.');
out('- P6 Coverage honesty: an unevaluated rule never scores better than the same rule passing.');
out('- P7 Applicability neutrality: an excluded dimension scores the same as an absent one.');
out('- P8 Stability: see the tolerance above.');
out();
for (const [axis, a] of Object.entries(report.axes)) {
  out(`## Axis: ${axis.replace(/_/g, ' ')}`);
  out();
  out(`*${a.question}*`);
  out();
  const props = [...new Set(a.options.flatMap((o) => Object.keys(o.properties)))];
  out(`| Option | ${props.map((p) => `${p} ${PROPS[p]}`).join(' | ')} | Scenarios | Max Δ (P8) |`);
  out(`|---|${props.map(() => '---').join('|')}|---|---|`);
  for (const o of a.options) {
    out(`| **${o.id}** ${o.describe}${o.id === a.leader ? ' ⭐' : ''} | ${props.map((p) => yes(o.properties[p]?.pass)).join(' | ')} | ${o.expectations_passed}/${o.expectations_total} | ${o.stability ?? '—'} |`);
  }
  out();
  out(a.leader_note);
  out();
  if (a.shared_failures.length) { out(`Failed by every option on this axis, so decided elsewhere and judged on the combined configuration: ${a.shared_failures.join('; ')}.`); out(); }
  const p4 = a.options.filter((o) => o.properties.P4).map((o) => `${o.id}: ${o.properties.P4.core_with_10_endpoints} → ${o.properties.P4.core_with_10000_endpoints}`);
  if (p4.length) { out(`Dilution (score of a defective core with a clean tail of 10 → 10,000 records): ${p4.join(' · ')}.`); out(); }
  const p3 = a.options.filter((o) => o.properties.P3 && !o.properties.P3.pass).map((o) => `${o.id} (${o.properties.P3.violation_count} case(s), e.g. "${o.properties.P3.violations[0]}")`);
  if (p3.length) { out(`Masking failures: ${p3.join('; ')}.`); out(); }
}
out('## The combined configuration');
out();
out('```json');
out(JSON.stringify(report.combined.configuration, null, 1));
out('```');
out();
out('| Property | Result |');
out('|---|---|');
for (const [k, v] of Object.entries(report.combined.properties)) out(`| ${k} ${PROPS[k]} | ${yes(v.pass)} |`);
out();
out('## Scenarios under the combined configuration');
out();
out('| Scenario | CMDB | ITSM | ITOM | Platform | Overall | Expectations |');
out('|---|---|---|---|---|---|---|');
for (const s of report.scenarios) {
  const m = (k) => (s.modules[k] ? `${s.modules[k].score}${s.modules[k].participates ? '' : ' (excluded)'}` : '—');
  const note = ALL_SCENARIOS.find((x) => x.id === s.id)?.note;
  out(`| **${s.id}** ${s.title} | ${m('cmdb')} | ${m('itsm')} | ${m('itom')} | ${m('platform')} | ${s.overall.score} (${s.overall.band}) | ${note ? `*informational: ${note}*` : s.expectations.map((e) => `${e.pass ? '✓' : '✗'} ${e.expectation}`).join('<br>')} |`);
}
out();
out('## Not calibrated here');
out();
out('- **Dimension and module weights.** The workbook states the CMDB (D1–D10) and Enterprise DQ (Q1–Q7) weights, and they are used as stated. ITSM, ITOM and Platform dimension weights and the module weights stay provisionally equal, marked "not reviewed", until SAOS supplies them (D-004).');
out('- **Recorded PDI runs.** A run stores rule outcomes, but not the per-rule measured values that Method C needs. Phase 4 records them, and they join this library then. Meanwhile the faithful scenarios (S01F–S13F) use the real catalogue and the workbook thresholds.');
out();

const DOC = path.resolve(HERE, '../../docs/HEALTH-ASSIST-CALIBRATION.md');
fs.writeFileSync(DOC, `${lines.join('\n')}\n`);
process.stdout.write(`calibration: combined ${JSON.stringify(report.combined.picks)} — ${report.combined.passes_all ? 'passes everything' : `${report.combined.failing.length} failing`}; promoted: ${report.promoted}\n  → ${path.relative(process.cwd(), path.join(SCORING, 'calibration-report.json'))}\n  → ${path.relative(process.cwd(), DOC)}\n`);
